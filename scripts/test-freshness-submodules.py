def work_left() -> float:
    """Seconds before the shared runner's exported absolute deadline, less a
    shutdown margin. Never a fresh process-relative budget."""
    deadline = int(os.environ["OXIDE_PROOF_DEADLINE_NS"])
    left = (deadline - time.clock_gettime_ns(time.CLOCK_UPTIME_RAW)) / 1e9 - SHUTDOWN_MARGIN_S
    if left <= 5:
        fail("work deadline reached before the runner's shutdown margin")
    return left


def write_tree(root: str, files: dict[str, str]) -> str:
    for relative, contents in files.items():
        path = os.path.join(root, relative)
        os.makedirs(os.path.dirname(path), exist_ok=True)
        with open(path, "w", encoding="utf-8") as handle:
            handle.write(contents)
    return os.path.realpath(root)


def private_environment(proof: Proof) -> dict:
    """The guarded command's own environment: private HOME, CARGO_HOME, pool
    and no inherited wrapper or target override."""
    env = dict(os.environ)
    for name in list(env):
        if name.startswith(("SCCACHE_", "CARGO_BUILD_", "CARGO_TARGET_")) or name in (
            "CARGO",
            "RUSTC",
            "RUSTC_WRAPPER",
            "RUSTC_WORKSPACE_WRAPPER",
        ):
            env.pop(name)
    # A private HOME must not move rustup's toolchain store.
    rustup = os.environ.get("RUSTUP_HOME") or os.path.join(
        os.path.expanduser("~"), ".rustup"
    )
    env.update(
        {
            "HOME": os.path.join(proof.root, "home"),
            "CARGO_HOME": os.path.join(proof.root, "cargo-home"),
            "RUSTUP_HOME": rustup,
            "OXIDE_POOL": os.path.join(proof.root, "pool"),
            "OXIDE_POOL_CAP": POOL_CAP,
            "RUSTUP_TOOLCHAIN": BUILDER,
            "RUSTUP_AUTO_INSTALL": "0",
            "RUSTC_WRAPPER": "",
            "RUSTC_WORKSPACE_WRAPPER": "",
            "CARGO_BUILD_RUSTC_WRAPPER": "",
            "CARGO_NET_OFFLINE": "true",
            "SUB_PROOF_LOG": os.path.join(proof.root, "marker.log"),
        }
    )
    return env


class Fixture:
    """Owned scratch Git repositories and the private Oxide environment."""

    def __init__(self, proof: Proof, candidate: str):
        self.proof = proof
        self.candidate = candidate
        self.root = proof.root
        self.env = private_environment(proof)
        for name in ("home", "cargo-home"):
            os.makedirs(os.path.join(self.root, name))
        self.log = os.path.join(self.root, "marker.log")

    def git(self, cwd: str, *args: str, allow_file: bool = False) -> str:
        command = ["git"]
        if allow_file:
            command += ["-c", "protocol.file.allow=always"]
        command += list(args)
        result = self.proof.run(command, cwd=cwd, env=self.env, timeout=60)
        expect(
            result.returncode == 0,
            f"git {' '.join(args)} failed in {cwd}: "
            f"{result.stderr.decode(errors='replace')[-800:]}",
        )
        return result.stdout.decode(errors="replace")

    def repo(self, root: str, files: dict[str, str], message: str) -> None:
        write_tree(root, files)
        self.git(root, "init", "--quiet", "-b", "main")
        self.git(root, "config", "user.email", "oxide-proof@example.invalid")
        self.git(root, "config", "user.name", "Oxide proof")
        self.git(root, "add", "-A")
        self.git(root, "commit", "--quiet", "-m", message)

    def build(self, cwd: str, label: str):
        result = self.proof.run(
            [self.candidate, "build", "--locked"], cwd=cwd, env=self.env, timeout=120
        )
        stderr = result.stderr.decode(errors="replace")
        print(f"build {label}: exit {result.returncode}", flush=True)
        for line in stderr.strip().splitlines()[-4:]:
            print(f"  {line}", flush=True)
        expect(result.returncode == 0, f"{label}: build failed: {stderr[-1200:]}")
        return stderr

    def binary(self, cwd: str, label: str) -> str:
        path = os.path.join(cwd, "target", "debug", "app")
        expect(os.path.isfile(path), f"{label}: no binary at {path}")
        result = self.proof.run([path], cwd=cwd, timeout=30)
        expect(result.returncode == 0, f"{label}: binary failed: {result.stderr!r}")
        return result.stdout.decode(errors="replace").strip()

    def marker_lines(self) -> list[str]:
        if not os.path.exists(self.log):
            return []
        with open(self.log, encoding="utf-8") as handle:
            return [line for line in handle.read().splitlines() if line]

    def read(self, path: str) -> str:
        with open(path, encoding="utf-8") as handle:
            return handle.read()

    def write(self, path: str, text: str) -> None:
        with open(path, "w", encoding="utf-8") as handle:
            handle.write(text)

    def age(self, path: str) -> None:
        os.utime(path, ns=(ANCIENT_NS, ANCIENT_NS))

    def mtime(self, path: str) -> int:
        return os.stat(path).st_mtime_ns

    def fingerprint(self, top: str) -> list[tuple]:
        """Every worktree path except Git's own store and the ignored build
        output, with its mode, mtime and raw bytes. A new path, changed byte
        or changed mtime shows up; an unreadable file is compared by name."""
        entries = []
        for current, directories, files in os.walk(top):
            relative_root = os.path.relpath(current, top)
            directories[:] = sorted(
                name
                for name in directories
                if name != ".git" and not (relative_root == "." and name == "target")
            )
            for name in sorted(files):
                path = os.path.join(current, name)
                relative = os.path.normpath(os.path.join(relative_root, name))
                metadata = os.lstat(path)
                try:
                    with open(path, "rb") as handle:
                        digest = hashlib.sha256(handle.read()).hexdigest()
                except OSError:
                    digest = "unreadable"
                entries.append((relative, metadata.st_mode, metadata.st_mtime_ns, digest))
        return entries


def committed(fixture: Fixture, cwd: str) -> str:
    return fixture.git(cwd, "rev-parse", "HEAD").strip()


def prove_two_states(fixture: Fixture) -> None:
    """The two supported states across two worktrees and two submodule
    commits, plus one same-checkout different-gitlink transition."""
    scratch = fixture.root
    child_origin = os.path.join(scratch, "sub-origin")
    child = os.path.join(child_origin, "work")
    os.makedirs(child_origin)
    fixture.repo(child, CHILD, "child one")
    c1 = committed(fixture, child)
    fixture.write(os.path.join(child, "value.txt"), "two\n")
    fixture.git(child, "commit", "--quiet", "-am", "child two")
    c2 = committed(fixture, child)
    expect(c1 != c2, "the child fixture has only one commit")

    primary = os.path.join(scratch, "super")
    fixture.repo(primary, APP, "fixture one")
    fixture.git(
        primary, "submodule", "add", "--quiet", "../sub-origin/work", "sub", allow_file=True
    )
    fixture.git(primary, "commit", "--quiet", "-m", "add submodule")
    fixture.git(primary, "submodule", "update", "--init", "--quiet")
    baseline = committed(fixture, primary)
    other = os.path.join(scratch, "wt-b")
    fixture.git(primary, "worktree", "add", "--quiet", other)
    expect(
        os.path.isdir(os.path.join(primary, "sub"))
        and bool(os.listdir(os.path.join(primary, "sub"))),
        "the primary checkout is not initialized",
    )
    expect(
        os.path.isdir(os.path.join(other, "sub"))
        and not os.listdir(os.path.join(other, "sub")),
        "the second worktree is not an empty uninitialized submodule",
    )
    print(f"fixture: primary {baseline}, child {c1} -> {c2}", flush=True)

    def cross_build(where: str, label: str) -> str:
        stderr = fixture.build(where, label)
        expect(
            "freshness gate refreshed" in stderr
            and "from another checkout's build" in stderr
            and LIMIT_NOTE in stderr,
            f"{label}: summary lacks the cross gate and its limit: {stderr[-800:]}",
        )
        return stderr

    def gated_build(where: str, label: str, *, gated: bool) -> str:
        stderr = fixture.build(where, label)
        if gated:
            expect("freshness gate" in stderr, f"{label}: a change ran no gate")
        else:
            expect("freshness gate" not in stderr, f"{label}: an unchanged repeat ran a gate")
        return stderr

    # 1. Cold Exact build; the executed marker runs once.
    stderr = fixture.build(primary, "primary cold exact")
    expect("freshness gate" not in stderr, "a new slot reported a gate")
    expect(fixture.binary(primary, "primary cold") == "one|shared one", "cold binary is stale")
    expect(fixture.marker_lines() == ["one|shared one"], f"marker {fixture.marker_lines()}")

    # 2. Same state, same checkout: no gate, no rebuild, no marker line.
    gated_build(primary, "primary unchanged", gated=False)
    expect(fixture.binary(primary, "primary unchanged") == "one|shared one", "repeat binary")
    expect(fixture.marker_lines() == ["one|shared one"], "unchanged repeat reran the marker")

    # 3. Exact -> Uninitialized across checkouts: the primary's slot moves to
    # the worktree, whose absent input must not reuse an initialized unit.
    cross_build(other, "uninitialized worktree")
    expect(
        fixture.binary(other, "uninitialized worktree") == "absent|shared one",
        "the uninitialized worktree reused an initialized unit",
    )
    expect(fixture.marker_lines()[-1] == "absent|shared one", "the marker did not rerun")

    # 4. Uninitialized origin, Exact current: the primary must not reuse the
    # worktree's absent unit even though its own child files are older.
    cross_build(primary, "primary after uninitialized origin")
    expect(
        fixture.binary(primary, "primary after uninitialized origin") == "one|shared one",
        "the primary reused the uninitialized unit",
    )
    expect(fixture.marker_lines()[-1] == "one|shared one", "the marker did not rerun on exact")

    # 5. Both directions in one checkout: deinit to an empty directory and
    # re-init, with the executed marker proving each rebuild.
    fixture.git(primary, "submodule", "deinit", "-f", "--quiet", "sub")
    expect(not os.listdir(os.path.join(primary, "sub")), "deinit left child content")
    gated_build(primary, "primary deinitialized", gated=True)
    expect(
        fixture.binary(primary, "primary deinitialized") == "absent|shared one",
        "the deinitialized build kept the old unit",
    )
    fixture.git(primary, "submodule", "update", "--init", "--quiet")
    gated_build(primary, "primary reinitialized", gated=True)
    expect(
        fixture.binary(primary, "primary reinitialized") == "one|shared one",
        "the reinitialized build reused the absent unit",
    )
    expect(fixture.marker_lines()[-1] == "one|shared one", "the marker did not rerun on reinit")

    # 6. A different gitlink in one checkout: the committed tree changes and
    # the child's own tracked file is made older than the gate's anchor, so
    # only the gate's per-file refresh can invalidate it.
    fixture.git(os.path.join(primary, "sub"), "checkout", "--quiet", c2)
    fixture.git(primary, "add", "sub")
    fixture.git(primary, "commit", "--quiet", "-m", "submodule to child two")
    expect(
        fixture.git(primary, "status", "--porcelain").strip() == "",
        "the primary checkout is dirty after the gitlink commit",
    )
    fixture.age(os.path.join(primary, "sub", "value.txt"))
    before = len(fixture.marker_lines())
    stderr = gated_build(primary, "primary different gitlink", gated=True)
    expect(
        "freshness gate refreshed" in stderr,
        f"the different gitlink did not refresh the child's files: {stderr[-800:]}",
    )
    expect(
        fixture.binary(primary, "primary different gitlink") == "two|shared one",
        "the different gitlink kept the old child content",
    )
    expect(len(fixture.marker_lines()) == before + 1, "the marker did not rerun")

    # 7. Same new state again: no gate and no rebuild.
    gated_build(primary, "primary second commit unchanged", gated=False)
    expect(
        fixture.binary(primary, "primary second commit unchanged") == "two|shared one",
        "the repeat after the new gitlink is stale",
    )
    expect(len(fixture.marker_lines()) == before + 1, "the repeat reran the marker")

    # 8. Stale-mtime regression across checkouts: the primary edits a plain
    # tracked file and builds; the worktree's differing copy is older than
    # that build and the gate refreshes it without changing its content.
    fixture.write(os.path.join(primary, "shared.txt"), "shared two\n")
    fixture.build(primary, "primary shared edit")
    expect(
        fixture.binary(primary, "primary shared edit") == "two|shared two", "the edit is stale"
    )
    stale = os.path.join(other, "shared.txt")
    stale_mtime = fixture.mtime(stale)
    before = len(fixture.marker_lines())
    cross_build(other, "worktree stale shared file")
    expect(
        fixture.binary(other, "worktree stale shared file") == "absent|shared one",
        "the worktree reused the primary's differing file",
    )
    expect(fixture.read(stale) == "shared one\n", "the gate changed the worktree's content")
    expect(fixture.mtime(stale) > stale_mtime, "the gate did not refresh the old file")
    expect(len(fixture.marker_lines()) == before + 1, "the stale build did not rerun")
    print(
        f"two-state proof held: {len(fixture.marker_lines())} executed markers, "
        f"primary at {fixture.git(primary, 'rev-parse', 'HEAD').strip()}",
        flush=True,
    )


def prove_refusals(fixture: Fixture) -> None:
    """Dirty, untracked, a different HEAD, an unmerged gitlink, an unreadable
    submodule and a nested gitlink refuse the slot and leave the source paths,
    bytes and mtimes untouched."""
    scratch = fixture.root
    child_origin = os.path.join(scratch, "refuse-child")
    child = os.path.join(child_origin, "work")
    os.makedirs(child_origin)
    fixture.repo(child, CHILD, "refusal child one")
    r1 = committed(fixture, child)
    fixture.write(os.path.join(child, "value.txt"), "two\n")
    fixture.git(child, "commit", "--quiet", "-am", "refusal child two")
    r2 = committed(fixture, child)
    nested_origin = os.path.join(scratch, "nested-origin")
    os.makedirs(nested_origin)
    fixture.repo(nested_origin, CHILD, "nested origin")

    top = os.path.join(scratch, "refuse-super")
    fixture.repo(top, REFUSAL, "refusal fixture")
    fixture.git(
        top, "submodule", "add", "--quiet", "../refuse-child/work", "sub", allow_file=True
    )
    fixture.git(top, "commit", "--quiet", "-m", "add refusal submodule")
    fixture.git(top, "submodule", "update", "--init", "--quiet")
    sub = os.path.join(top, "sub")
    print(f"refusal fixture: {committed(fixture, top)}, child {r1}", flush=True)

    def assert_refused(label: str, mutate, revert) -> None:
        fixture.build(top, f"{label} baseline")
        mutate()
        before = fixture.fingerprint(top)
        stderr = fixture.build(top, label)
        expect(
            "freshness gate cannot vouch" in stderr
            or "freshness gate refused another checkout's slot" in stderr,
            f"{label}: the gate did not refuse the slot: {stderr[-1200:]}",
        )
        after = fixture.fingerprint(top)
        if after != before:
            changed = [entry[0] for entry in after if entry not in before]
            fail(f"{label}: the refusal mutated source: {changed[:8]}")
        revert()
        print(f"refused as expected and source untouched: {label}", flush=True)

    assert_refused(
        "dirty submodule",
        lambda: fixture.write(os.path.join(sub, "extra.rs"), "pub const EXTRA: u8 = 2;\n"),
        lambda: fixture.git(sub, "checkout", "--quiet", "--", "extra.rs"),
    )
    assert_refused(
        "untracked submodule file",
        lambda: fixture.write(os.path.join(sub, "untracked.txt"), "stray\n"),
        lambda: os.unlink(os.path.join(sub, "untracked.txt")),
    )
    assert_refused(
        "different child HEAD",
        lambda: fixture.git(sub, "checkout", "--quiet", r2),
        lambda: fixture.git(sub, "checkout", "--quiet", r1),
    )

    def conflict() -> None:
        records = os.path.join(scratch, "conflict.index-info")
        fixture.write(
            records,
            f"160000 {r1} 1\tsub\n160000 {r1} 2\tsub\n160000 {r1} 3\tsub\n",
        )
        result = fixture.proof.run(
            ["/bin/sh", "-c", f'git update-index --index-info < "{records}"'],
            cwd=top,
            env=fixture.env,
            timeout=60,
        )
        expect(result.returncode == 0, f"conflict setup failed: {result.stderr!r}")

    assert_refused(
        "unmerged gitlink",
        conflict,
        lambda: fixture.git(top, "reset", "--quiet", "--hard", "HEAD"),
    )

    pointer = os.path.join(sub, ".git")
    assert_refused(
        "unreadable submodule gitdir",
        lambda: os.chmod(pointer, 0o000),
        lambda: os.chmod(pointer, 0o644),
    )
    # Nested gitlink last: advancing the child to a commit with its own
    # submodule needs no revert after this proof's final refusal.
    fixture.build(top, "nested baseline")
    fixture.git(
        child, "submodule", "add", "--quiet", "../nested-origin", "nested", allow_file=True
    )
    fixture.git(child, "add", "-A")
    fixture.git(child, "commit", "--quiet", "-m", "nested child")
    r3 = committed(fixture, child)
    fixture.git(sub, "checkout", "--quiet", r3)
    fixture.git(top, "add", "sub")
    fixture.git(top, "commit", "--quiet", "-m", "nested gitlink")
    before = fixture.fingerprint(top)
    stderr = fixture.build(top, "nested child gitlink")
    expect(
        "freshness gate cannot vouch for slot" in stderr and "nested submodule" in stderr,
        f"nested: the gate did not name the nested gitlink: {stderr[-1200:]}",
    )
    expect(fixture.fingerprint(top) == before, "nested: the refusal mutated source")
    print(f"refused as expected and source untouched: nested child gitlink ({r3})", flush=True)


def repo_head(proof: Proof, repo: str) -> str:
    result = proof.run(["git", "rev-parse", "HEAD"], cwd=repo, timeout=30)
    expect(result.returncode == 0, "cannot read the candidate HEAD")
    return result.stdout.decode().strip()


def run(proof: Proof, repo: str) -> None:
    source = repo_head(proof, repo)
    dirty = (
        proof.run(["git", "status", "--porcelain"], cwd=repo, timeout=60)
        .stdout.decode()
        .strip()
    )
    expect(not dirty, f"candidate checkout is not clean: {dirty}")
    print(f"freshness-submodules proof {os.getpid()} source {source}", flush=True)
    proof.phase("start")
    candidate = stage_at(proof, repo, "oxide-candidate")
    print(f"staged candidate sha256 {sha256(candidate)}", flush=True)
    print(
        "source facts: "
        + ", ".join(
            f"{name} {sha256(os.path.join(repo, name))[:16]}"
            for name in ("Cargo.toml", "Cargo.lock")
        ),
        flush=True,
    )
    proof.phase("staged")
    fixture = Fixture(proof, candidate)
    prove_two_states(fixture)
    proof.phase("two states")
    prove_refusals(fixture)
    proof.phase("refusals")


def terminated(signum, frame) -> None:
    fail(f"terminated by signal {signum}")


def overdue(signum, frame) -> None:
    fail("the proof exceeded its work window")


def record(name: str, text: str) -> None:
    evidence = os.environ.get("OXIDE_PROOF_EVIDENCE")
    if evidence and os.path.isdir(evidence):
        with open(os.path.join(evidence, name), "w", encoding="utf-8") as handle:
            handle.write(text)


