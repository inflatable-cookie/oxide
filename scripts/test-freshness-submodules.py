#!/usr/bin/env python3
"""Focused submodule freshness proof for oxide#119.

A short fixed script under the qualified shared proof supervisor
(`scripts/bounded-test.py`, SHA-256
d89115f1ca03587e1d9134efa153cc9c94860d2904f52e2a11bc8c8fbe21f25e), which
owns the 300 s deadline, 512 MiB monitored scratch, process closure and
cleanup. It reuses the reviewed oxide#104 staging helper and the #105/#104
guarded child runner; it adds no supervision of its own.

Stages this clean HEAD's `oxide` offline with 1.97.1 and, only with owned
local Git repositories and submodule layouts, proves the narrow two-state
submodule contract of the freshness gate:

- an initialized-clean submodule at the declared gitlink is `Exact`; a
  positively absent or empty uninitialized directory is `Uninitialized`;
  both persist distinct state, so one tree never matches across them;
- same-state clean reuse is a no-op and reruns no executed marker;
- Exact -> Uninitialized and Uninitialized -> Exact both rebuild the executed
  marker and leave no stale binary, across checkouts and in one checkout;
- a different gitlink rebuilds, and the gate's own refresh invalidates an old
  innermost input (the child's tracked files are refreshed);
- a differing old plain checkout file is still refreshed (stale-mtime
  regression), local packages and the limit note keep their summaries;
- dirty, untracked, a different child HEAD, an unmerged gitlink, an
  unreadable submodule and a nested gitlink all refuse the slot and leave the
  source paths, bytes and mtimes untouched.

No live Effigy checkout, no `submodule init`/`update`/fetch by the product
gate (fixtures are set up before it runs), no network and no removable
volume. Not a benchmark and not full QA.
"""

